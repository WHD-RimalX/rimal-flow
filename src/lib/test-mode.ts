/**
 * وضع التجربة — لتسهيل اختبار السيناريوهات الزمنية بلا انتظار ساعات.
 *
 * يُرخي **القيود الزمنية فقط**: نافذة الوصول (±30 دقيقة حول موعد الحجز) ونافذة
 * الباقة الشهرية اليومية. كل ما عداه يبقى مفعّلاً كما هو بلا استثناء: آلة الحالة،
 * ذرية العمليات، استهلاك رمز المسح لمرة واحدة، الصلاحيات، وفحص التعارض.
 *
 * أمان بالتصميم: لا يمكن تفعيله في الإنتاج إطلاقاً — الشرط الأول يرفض حتى لو
 * ضُبط المتغير على Vercel بالخطأ. للتجربة استخدم بيئة محلية أو نشر Preview.
 *
 * التفعيل محلياً: أضف RELAX_ATTENDANCE_WINDOW="true" في ملف .env ثم أعد تشغيل الخادم.
 */
export function isAttendanceWindowRelaxed(): boolean {
  if (process.env.NODE_ENV === "production") return false;
  return process.env.RELAX_ATTENDANCE_WINDOW === "true";
}
